package io.github.aplite36.chunkcarts.fabric;

import io.github.aplite36.chunkcarts.core.WorldId;
import io.github.aplite36.chunkcarts.core.platform.CartView;
import io.github.aplite36.chunkcarts.core.platform.WorldQuery;
import net.minecraft.core.BlockPos;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.tags.BlockTags;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.level.chunk.storage.SerializableChunkData;
import org.jetbrains.annotations.Nullable;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;

/**
 * The read-only half of the platform surface (SPEC §1.1).
 */
final class FabricWorldQuery implements WorldQuery {

    /**
     * How many "this chunk exists on disk" answers to remember. Each entry is a long and a boolean;
     * four thousand of them cost nothing and cover a very long route, and the bound is what stops a
     * server that has been up for a month from turning this into a slow memory leak.
     */
    private static final int GENERATED_CACHE_SIZE = 4096;

    private final MinecraftServer server;
    private final Map<String, ServerLevel> levels = new LinkedHashMap<>();

    private record ChunkKey(String world, long pos) {}

    /**
     * Chunks known to be generated. Positive answers only — see {@link #isGenerated}. Access-ordered
     * so the bound evicts the part of the world the carts have left rather than the part they are in.
     */
    private final Map<ChunkKey, Boolean> generated = new LinkedHashMap<>(256, 0.75f, true) {
        @Override
        protected boolean removeEldestEntry(Map.Entry<ChunkKey, Boolean> eldest) {
            return size() > GENERATED_CACHE_SIZE;
        }
    };

    FabricWorldQuery(MinecraftServer server) {
        this.server = server;
        for (ServerLevel level : server.getAllLevels()) {
            levels.put(FabricCartView.worldIdOf(level).value(), level);
        }
    }

    @Nullable
    ServerLevel level(WorldId id) {
        return levels.get(id.value());
    }

    /**
     * Whether the chunk already exists on disk. ChunkCarts refuses to generate terrain, both to
     * avoid worldgen-bot abuse and to keep world folders from bloating (SPEC §5).
     *
     * <p>Three tiers, cheapest first. A loaded chunk is generated by definition, and after the first
     * poll of a journey that covers the whole held region because we are holding it. A remembered
     * answer costs a map lookup. Only a chunk that is neither — the frontier the cart is about to
     * enter, three of them per boundary crossing — reaches the region file, and that read blocks the
     * server thread until the IO worker services it.
     *
     * <p>The blocking read is deliberate and is the same trade Paper makes inside
     * {@code World#isChunkGenerated}. The alternative is answering from a cache that has not been
     * filled yet, and there is no safe value to answer with: {@code false} terminates a healthy
     * journey as {@code UNGENERATED_CHUNK}, and {@code true} is how a cart gets used as the worldgen
     * bot this method exists to prevent.
     *
     * <p>Only positive answers are cached. A chunk that does not exist yet may exist later — someone
     * walks out there — and a stale negative would refuse a route across terrain that has since been
     * generated. Negatives are not a hot path anyway: the first one ends the journey.
     */
    @Override
    public boolean isGenerated(WorldId world, int cx, int cz) {
        ServerLevel level = level(world);
        // A world we do not know has nothing generated as far as we are concerned: refusing to
        // travel is the safe direction.
        if (level == null) {
            return false;
        }
        if (level.getChunkSource().hasChunk(cx, cz)) {
            return true;
        }

        ChunkKey key = new ChunkKey(world.value(), ChunkPos.pack(cx, cz));
        if (generated.containsKey(key)) {
            return true;
        }

        Optional<CompoundTag> stored = level.getChunkSource().chunkMap.read(new ChunkPos(cx, cz)).join();
        // Present-but-unfinished is not generated. A proto-chunk saved mid-generation still needs
        // the rest of the pipeline run on it, which is exactly the work this refuses to trigger.
        boolean exists = stored.isPresent()
                && SerializableChunkData.getChunkStatusFromTag(stored.get()) == ChunkStatus.FULL;
        if (exists) {
            generated.put(key, Boolean.TRUE);
        }
        return exists;
    }

    /**
     * <strong>Answered from player positions, never from chunk load state (SPEC §3.3).</strong>
     *
     * <p>This is the load-bearing line of the whole adapter. Chunks ChunkCarts holds are loaded, and
     * loaded at entity-ticking level, so asking whether the chunk is loaded here would report true
     * for our own tickets: carts would grant themselves tokens, the scheme would be circular, and
     * every rule downstream of it would be decorative while still compiling and appearing to work.
     * The §9 suite cannot catch that mistake — it runs against a fake — so the guarantee lives here.
     */
    @Override
    public boolean isPlayerLoaded(WorldId world, int cx, int cz) {
        ServerLevel level = level(world);
        if (level == null) {
            return false;
        }
        // Simulation distance, not view distance: the question is whether the chunk is being ticked
        // because of this player, which is what "loaded by a player" has to mean for a token to be
        // worth anything. It is a server-wide setting here rather than per-player as on Paper.
        int simulation = Math.max(1, server.getPlayerList().getSimulationDistance());
        for (ServerPlayer player : level.players()) {
            // Chebyshev distance, which is what a square simulation radius means and what
            // getChessboardDistance computes — not the Euclidean one.
            if (player.chunkPosition().getChessboardDistance(cx, cz) <= simulation) {
                return true;
            }
        }
        return false;
    }

    /**
     * Nothing to do on this platform, and the reason is worth writing down.
     *
     * <p>SPEC §5 wants the ring ahead requested asynchronously so a boundary crossing never triggers
     * a synchronous chunk load. On Paper that is a real call, because {@code addPluginChunkTicket}
     * can load a chunk on the calling thread. Here it cannot: {@code addTicketWithRadius} only
     * records the ticket in the level's {@code TicketStorage}, and the chunk is promoted later by
     * the chunk source's own update pass — verified by reading both methods in the 26.2 sources.
     * Holding a chunk <em>is</em> the asynchronous request, so there is nothing to await and nothing
     * to ask for ahead of it.
     *
     * <p>The one API that would load on demand, {@code addTicketAndLoadWithRadius}, forces a
     * distance-manager update per call and generates missing terrain. Using it would be slower and
     * would undo {@link #isGenerated}.
     */
    @Override
    public CompletableFuture<Void> prefetch(WorldId world, int cx, int cz) {
        return CompletableFuture.completedFuture(null);
    }

    @Override
    public boolean isOnRail(CartView cart) {
        ServerLevel level = level(cart.world());
        if (level == null) {
            return false;
        }
        BlockPos at = BlockPos.containing(cart.x(), cart.y(), cart.z());
        // A minecart rides slightly above the rail, and which of the two blocks its position rounds
        // into depends on the rail shape and the tick. Checking both is what stops a cart on a slope
        // being reported as derailed every few polls.
        return level.getBlockState(at).is(BlockTags.RAILS)
                || level.getBlockState(at.below()).is(BlockTags.RAILS);
    }
}
